namespace KernSmith.Font.Brotli;

/// <summary>
/// Literal context-ID lookup tables from RFC 7932 section 7.1. <c>ManagedBrotliDecoderTests</c>
/// pins each table to the CRC-32 the RFC publishes for it.
/// </summary>
internal static class BrotliContext
{
    /// <summary>Context mode LSB6: the six low bits of the previous byte.</summary>
    public const int ModeLsb6 = 0;

    /// <summary>Context mode MSB6: the six high bits of the previous byte.</summary>
    public const int ModeMsb6 = 1;

    /// <summary>Context mode UTF8: <c>Lut0[p1] | Lut1[p2]</c>.</summary>
    public const int ModeUtf8 = 2;

    /// <summary>Context mode Signed: <c>(Lut2[p1] &lt;&lt; 3) | Lut2[p2]</c>.</summary>
    public const int ModeSigned = 3;

    /// <summary>Computes the literal context ID (0..63) for a context mode and the last two output bytes.</summary>
    public static int LiteralContextId(int mode, byte p1, byte p2) => mode switch
    {
        ModeLsb6 => p1 & 0x3f,
        ModeMsb6 => p1 >> 2,
        ModeUtf8 => Lut0[p1] | Lut1[p2],
        _ => (Lut2[p1] << 3) | Lut2[p2],
    };

    /// <summary>
    /// <see cref="LiteralContextId"/> split into two lookups per mode, for the decode loop:
    /// <c>LiteralContextId(mode, p1, p2) == SplitLookup[mode * 512 + p1] | SplitLookup[mode * 512 + 256 + p2]</c>.
    /// Every mode's formula ORs a <c>p1</c> part with a disjoint <c>p2</c> part (zero for the
    /// LSB6 and MSB6 modes), so no branch on the mode is needed per literal.
    /// </summary>
    public static readonly byte[] SplitLookup = BuildSplitLookup();

    private static byte[] BuildSplitLookup()
    {
        var table = new byte[4 * 512];
        for (var b = 0; b < 256; b++)
        {
            table[(ModeLsb6 << 9) + b] = (byte)(b & 0x3f);
            table[(ModeMsb6 << 9) + b] = (byte)(b >> 2);
            table[(ModeUtf8 << 9) + b] = Lut0[b];
            table[(ModeUtf8 << 9) + 256 + b] = Lut1[b];
            table[(ModeSigned << 9) + b] = (byte)(Lut2[b] << 3);
            table[(ModeSigned << 9) + 256 + b] = Lut2[b];
        }

        return table;
    }

