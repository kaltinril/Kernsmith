    /// <summary>Computes the literal context ID (0..63) for a context mode and the last two output bytes.</summary>
    public static int LiteralContextId(int mode, byte p1, byte p2) => mode switch
    {
        ModeLsb6 => p1 & 0x3f,
        ModeMsb6 => p1 >> 2,
        ModeUtf8 => Lut0[p1] | Lut1[p2],
        _ => (Lut2[p1] << 3) | Lut2[p2],
    };

